"""Build the offline high-frequency word table from Android PinyinIME.

Download the pinned URL below and base64-decode the response, then run:
    python tools/generate_pinyin_aosp_words.py rawdict_utf16_65105_freq.txt
Add --check to compare against the checked-in output without writing it.
"""

import argparse
from collections import defaultdict
from hashlib import sha256
from pathlib import Path
import re

from generate_pinyin_unihan import ASSETS, ROW, font_codepoints


AOSP_URL = (
    "https://android.googlesource.com/platform/packages/inputmethods/PinyinIME/"
    "+/refs/tags/android-sdk-4.4.2_r1.0.1/jni/data/rawdict_utf16_65105_freq.txt?format=TEXT"
)
AOSP_SHA256 = "408700f28a56091fa07f3b849a0f134fbfc71e6b2ae9b3f52973a5b076f599ff"
WORD_LIMIT = 8000
READING = re.compile(r"[a-z]{1,6}\Z")


def curated_words():
    return {
        (spelling, word)
        for filename in ("pinyin_phrases.inc", "pinyin_daily.inc")
        for spelling, text in ROW.findall((ASSETS / filename).read_text(encoding="utf-8"))
        for word in text.split("|")
    }


def read_word_frequencies(path, renderable):
    raw = path.read_bytes()
    if sha256(raw).hexdigest() != AOSP_SHA256:
        raise ValueError(f"Expected the base64-decoded Android PinyinIME dictionary from {AOSP_URL}")

    curated = curated_words()
    by_pronunciation = {}
    for line in raw.decode("utf-16").splitlines():
        word, frequency, gbk_flag, *readings = line.split()
        if gbk_flag != "0" or not 2 <= len(word) <= 4:
            continue
        if not all(0x3400 <= ord(char) <= 0x9FFF and ord(char) in renderable for char in word):
            continue
        if len(readings) != len(word) or not all(READING.fullmatch(reading) for reading in readings):
            raise ValueError(f"Invalid source pronunciation for {word!r}")
        key = "".join(readings), word
        if key not in curated:
            by_pronunciation[key] = max(float(frequency), by_pronunciation.get(key, 0.0))
    return by_pronunciation


def generate(path):
    renderable = font_codepoints(ASSETS / "font_16.c") & font_codepoints(ASSETS / "font_24.c")
    frequencies = read_word_frequencies(path, renderable)
    ordered = sorted(frequencies, key=lambda key: (-frequencies[key], key))[:WORD_LIMIT]
    words_by_spelling = defaultdict(list)
    for spelling, word in ordered:
        words_by_spelling[spelling].append(word)

    data = "".join(
        f'    {{"{spelling}", "{"|".join(words_by_spelling[spelling])}"}},\n'
        for spelling in sorted(words_by_spelling)
    )
    generated = (
        "/* Generated by tools/generate_pinyin_aosp_words.py.\n"
        " * Adapted from Android PinyinIME, Copyright (c) 2009 The Android Open Source Project.\n"
        " * See pinyin_aosp_words.LICENSE.txt for Apache-2.0 terms and source. */\n"
        f"{data}"
    ).encode("utf-8")
    return generated, len(ordered), len(words_by_spelling), len({word for _, word in ordered})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dictionary", type=Path, help="base64-decoded Android PinyinIME source")
    parser.add_argument("--check", action="store_true", help="compare with checked-in output")
    args = parser.parse_args()

    generated, readings, spellings, words = generate(args.dictionary)
    destination = ASSETS / "pinyin_aosp_words.inc"
    if args.check:
        if destination.read_bytes().replace(b"\r\n", b"\n") != generated:
            parser.error("pinyin_aosp_words.inc differs from regenerated output")
    else:
        destination.write_bytes(generated)
    print(f"{words} distinct words, {readings} word readings, {spellings} spellings")


if __name__ == "__main__":
    main()
